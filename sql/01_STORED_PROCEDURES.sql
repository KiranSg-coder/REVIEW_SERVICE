CREATE OR ALTER PROCEDURE [dbo].[USP_MODERATOR_QUEUE_OPEN]
(
    @REVIEW_PAGESIZE INT = 50,
    @REVIEW_PAGE    INT = 1,
    @PLAN_PAGESIZE  INT = 50,
    @PLAN_PAGE      INT = 1
)
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @R_OFF INT = (@REVIEW_PAGE - 1) * @REVIEW_PAGESIZE;
    DECLARE @P_OFF INT = (@PLAN_PAGE - 1) * @PLAN_PAGESIZE;

    ;WITH RF AS (
        SELECT R.*
        FROM dbo.REVIEW_REPORT R
        WHERE R.STATUS = N'OPEN'
    )
    SELECT *,
           COUNT(*) OVER() AS TOTALCOUNT
    FROM RF
    ORDER BY CREATEDDATE DESC
    OFFSET @R_OFF ROWS FETCH NEXT @REVIEW_PAGESIZE ROWS ONLY;

    ;WITH PC AS (
        SELECT P.*
        FROM dbo.PLAN_CONTENT_REPORT P
        WHERE P.STATUS = N'OPEN'
    )
    SELECT *,
           COUNT(*) OVER() AS TOTALCOUNTPLAN
    FROM PC
    ORDER BY CREATEDDATE DESC
    OFFSET @P_OFF ROWS FETCH NEXT @PLAN_PAGESIZE ROWS ONLY;
END
