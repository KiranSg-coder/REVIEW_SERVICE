-- ============================================================
-- USP_REVIEW_UPSERT
-- Create or update a learner review (one row per USERID+PLANID).
-- Eligibility (completed enrollment) enforced at API + Enrollment.
-- SCREEN L6 — post-completion rating prompt (FR-043).
-- ============================================================

CREATE OR ALTER PROCEDURE [dbo].[USP_REVIEW_UPSERT]
(
    @USERID                  BIGINT,
    @PLANID                  BIGINT,
    @PLANVERSION             INT,
    @ENROLLMENTID            BIGINT         = NULL,
    @RATING                  TINYINT,
    @TITLE                   NVARCHAR(200)  = NULL,
    @BODY                    NVARCHAR(4000) = NULL,
    @SUBMITTEDAFTERCOMPLETE  BIT            = 1,
    @ALLOWRESTOREVISIBLE     BIT            = 1
)
AS
BEGIN
    SET NOCOUNT ON;

    BEGIN TRY
        IF @RATING < 1 OR @RATING > 5
        BEGIN
            SELECT 0 AS SUCCESS, CAST(NULL AS BIGINT) AS REVIEWID,
                   N'Rating must be between 1 and 5' AS MESSAGE;
            RETURN;
        END

        DECLARE @REVIEWID BIGINT;
        DECLARE @CURVIS   NVARCHAR(30);

        SELECT @REVIEWID = REVIEWID, @CURVIS = VISIBILITYSTATUS
        FROM dbo.PLAN_USER_REVIEW
        WHERE USERID = @USERID AND PLANID = @PLANID;

        DECLARE @NEXTVIS NVARCHAR(30) =
            CASE
                WHEN @REVIEWID IS NULL THEN N'VISIBLE'
                WHEN @CURVIS IN (N'HIDDEN_ADMIN', N'UNDER_REVIEW') AND @ALLOWRESTOREVISIBLE = 1 THEN N'VISIBLE'
                ELSE @CURVIS
            END;

        IF @REVIEWID IS NULL
        BEGIN
            INSERT INTO dbo.PLAN_USER_REVIEW
            (
                USERID, PLANID, PLANVERSION, ENROLLMENTID,
                RATING, TITLE, BODY, VISIBILITYSTATUS,
                SUBMITTEDAFTERCOMPLETE, CREATEDDATE, UPDATEDDATE
            )
            VALUES
            (
                @USERID, @PLANID, @PLANVERSION, @ENROLLMENTID,
                @RATING, @TITLE, @BODY, N'VISIBLE',
                @SUBMITTEDAFTERCOMPLETE, SYSUTCDATETIME(), SYSUTCDATETIME()
            );

            SET @REVIEWID = SCOPE_IDENTITY();

            SELECT 1 AS SUCCESS, @REVIEWID AS REVIEWID, N'Review submitted' AS MESSAGE;
            RETURN;
        END

        UPDATE dbo.PLAN_USER_REVIEW
        SET PLANVERSION            = @PLANVERSION,
            ENROLLMENTID           = ISNULL(@ENROLLMENTID, ENROLLMENTID),
            RATING                 = @RATING,
            TITLE                  = @TITLE,
            BODY                   = @BODY,
            VISIBILITYSTATUS       = @NEXTVIS,
            SUBMITTEDAFTERCOMPLETE =
                CASE WHEN @SUBMITTEDAFTERCOMPLETE = 1 THEN 1 ELSE SUBMITTEDAFTERCOMPLETE END,
            UPDATEDDATE            = SYSUTCDATETIME()
        WHERE REVIEWID = @REVIEWID;

        SELECT 1 AS SUCCESS, @REVIEWID AS REVIEWID, N'Review updated' AS MESSAGE;
    END TRY
    BEGIN CATCH
        SELECT 0 AS SUCCESS, CAST(NULL AS BIGINT) AS REVIEWID, ERROR_MESSAGE() AS MESSAGE;
    END CATCH
END
GO


CREATE OR ALTER PROCEDURE [dbo].[USP_REVIEW_REMOVE_BY_USER]
(
    @USERID BIGINT,
    @PLANID BIGINT
)
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @REV BIGINT;
    SELECT @REV = REVIEWID
    FROM dbo.PLAN_USER_REVIEW
    WHERE USERID = @USERID AND PLANID = @PLANID;

    IF @REV IS NULL
    BEGIN
        SELECT 0 AS SUCCESS, N'No review found' AS MESSAGE;
        RETURN;
    END

    UPDATE dbo.PLAN_USER_REVIEW
    SET VISIBILITYSTATUS = N'REMOVED_BY_USER',
        UPDATEDDATE      = SYSUTCDATETIME()
    WHERE REVIEWID = @REV;

    SELECT 1 AS SUCCESS, N'Review removed by user' AS MESSAGE;
END
GO


