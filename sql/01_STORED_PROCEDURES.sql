CREATE OR ALTER PROCEDURE [dbo].[USP_REVIEW_REPORT_RESOLVE]
(
    @REPORTID         BIGINT,
    @MODERATORUSERID BIGINT,
    @NEWSTATUS       NVARCHAR(20),
    @MODERATORNOTE   NVARCHAR(1000) = NULL
)
AS
BEGIN
    SET NOCOUNT ON;

    IF @NEWSTATUS NOT IN (N'RESOLVED', N'DISMISSED')
    BEGIN
        SELECT 0 AS SUCCESS, N'NEWSTATUS must be RESOLVED or DISMISSED' AS MESSAGE;
        RETURN;
    END

    DECLARE @REVIEW BIGINT;
    SELECT @REVIEW = REVIEWID
    FROM dbo.REVIEW_REPORT
    WHERE REPORTID = @REPORTID;

    IF @REVIEW IS NULL
    BEGIN
        SELECT 0 AS SUCCESS, N'Report not found' AS MESSAGE;
        RETURN;
    END

    UPDATE dbo.REVIEW_REPORT
    SET STATUS           = @NEWSTATUS,
        RESOLVEDDATE     = SYSUTCDATETIME(),
        MODERATORUSERID  = @MODERATORUSERID,
        MODERATORNOTE    = @MODERATORNOTE
    WHERE REPORTID = @REPORTID;

    DECLARE @OPENFLAGS INT;
    SELECT @OPENFLAGS = COUNT(*)
    FROM dbo.REVIEW_REPORT
    WHERE REVIEWID = @REVIEW AND STATUS = N'OPEN';

    DECLARE @REVSTATUS NVARCHAR(30);
    SELECT @REVSTATUS = VISIBILITYSTATUS
    FROM dbo.PLAN_USER_REVIEW
    WHERE REVIEWID = @REVIEW;

    IF @NEWSTATUS = N'RESOLVED'
    BEGIN
        UPDATE dbo.PLAN_USER_REVIEW
        SET VISIBILITYSTATUS = N'HIDDEN_ADMIN',
            UPDATEDDATE      = SYSUTCDATETIME()
        WHERE REVIEWID = @REVIEW;
    END
    ELSE
    BEGIN
        IF @OPENFLAGS = 0 AND @REVSTATUS = N'UNDER_REVIEW'
        BEGIN
            UPDATE dbo.PLAN_USER_REVIEW
            SET VISIBILITYSTATUS = N'VISIBLE',
                UPDATEDDATE      = SYSUTCDATETIME()
            WHERE REVIEWID = @REVIEW;
        END
    END

    SELECT 1 AS SUCCESS, N'Moderator action saved' AS MESSAGE;
END
GO


