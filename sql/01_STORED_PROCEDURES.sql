CREATE OR ALTER PROCEDURE [dbo].[USP_REVIEW_LIST_BY_PLAN_PUBLIC]
(
    @PLANID     BIGINT,
    @PAGESIZE   INT = 20,
    @PAGENUMBER INT = 1
)
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @OFFSET INT = (@PAGENUMBER - 1) * @PAGESIZE;

    ;WITH Base AS (
        SELECT
            R.REVIEWID, R.USERID, R.RATING, R.TITLE, R.BODY,
            R.PLANVERSION, R.CREATEDDATE, R.UPDATEDDATE
        FROM dbo.PLAN_USER_REVIEW R
        WHERE R.PLANID = @PLANID
          AND R.VISIBILITYSTATUS = N'VISIBLE'
    )
    SELECT
        COUNT(*) OVER() AS TOTALCOUNT,
        REVIEWID, USERID, RATING, TITLE, BODY,
        PLANVERSION, CREATEDDATE, UPDATEDDATE
    FROM Base
    ORDER BY CREATEDDATE DESC
    OFFSET @OFFSET ROWS FETCH NEXT @PAGESIZE ROWS ONLY;
END
GO


CREATE OR ALTER PROCEDURE [dbo].[USP_REVIEW_STATS_BY_PLAN]
(
    @PLANID BIGINT
)
AS
BEGIN
    SET NOCOUNT ON;

    SELECT
        COUNT(*)                                          AS REVIEWCOUNT,
        AVG(CAST(RATING AS DECIMAL(4, 2)))              AS AVGRATING,
        SUM(CASE WHEN RATING >= 5 THEN 1 ELSE 0 END)      AS FIVESTARCOUNT,
        SUM(CASE WHEN RATING <= 2 THEN 1 ELSE 0 END)      AS LOWRATINGCOUNT
    FROM dbo.PLAN_USER_REVIEW
    WHERE PLANID = @PLANID
      AND VISIBILITYSTATUS = N'VISIBLE';
END
GO


