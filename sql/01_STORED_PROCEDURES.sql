CREATE OR ALTER PROCEDURE [dbo].[USP_REVIEW_MODERATOR_SET_VISIBILITY]
(
    @REVIEWID        BIGINT,
    @MODERATORUSERID BIGINT,
    @NEWVISIBILITY   NVARCHAR(30)
)
AS
BEGIN
    SET NOCOUNT ON;

