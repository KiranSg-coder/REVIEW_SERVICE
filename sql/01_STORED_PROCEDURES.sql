CREATE OR ALTER PROCEDURE [dbo].[USP_REVIEW_REPORT_SUBMIT]
(
    @REVIEWID         BIGINT,
    @REPORTEDBYUSERID BIGINT,
    @REASONCODE       NVARCHAR(50),
    @DETAIL           NVARCHAR(2000) = NULL
)
AS
BEGIN
    SET NOCOUNT ON;

    BEGIN TRY
        IF NOT EXISTS (SELECT 1 FROM dbo.PLAN_USER_REVIEW WHERE REVIEWID = @REVIEWID)
        BEGIN
            SELECT 0 AS SUCCESS, CAST(NULL AS BIGINT) AS REPORTID,
                   N'Review does not exist' AS MESSAGE;
            RETURN;
        END

        DECLARE @OWNER BIGINT;
        SELECT @OWNER = USERID FROM dbo.PLAN_USER_REVIEW WHERE REVIEWID = @REVIEWID;

        IF @OWNER = @REPORTEDBYUSERID
        BEGIN
            SELECT 0 AS SUCCESS, CAST(NULL AS BIGINT) AS REPORTID,
                   N'Cannot report your own review' AS MESSAGE;
            RETURN;
        END

        DECLARE @EXISTING BIGINT;
        SELECT @EXISTING = REPORTID
        FROM dbo.REVIEW_REPORT
        WHERE REVIEWID = @REVIEWID
          AND REPORTEDBYUSERID = @REPORTEDBYUSERID
          AND STATUS = N'OPEN';

        IF @EXISTING IS NOT NULL
        BEGIN
            UPDATE dbo.REVIEW_REPORT
            SET REASONCODE  = @REASONCODE,
                DETAIL      = ISNULL(@DETAIL, DETAIL)
            WHERE REPORTID = @EXISTING;

            UPDATE dbo.PLAN_USER_REVIEW
            SET VISIBILITYSTATUS = N'UNDER_REVIEW',
                UPDATEDDATE      = SYSUTCDATETIME()
            WHERE REVIEWID = @REVIEWID
              AND VISIBILITYSTATUS = N'VISIBLE';

            SELECT 1 AS SUCCESS, @EXISTING AS REPORTID,
                   N'Open flag updated for review' AS MESSAGE;
            RETURN;
        END

        INSERT INTO dbo.REVIEW_REPORT
        (REVIEWID, REPORTEDBYUSERID, REASONCODE, DETAIL, STATUS, CREATEDDATE)
        VALUES (@REVIEWID, @REPORTEDBYUSERID, @REASONCODE, @DETAIL,
                N'OPEN', SYSUTCDATETIME());

        DECLARE @RID BIGINT = SCOPE_IDENTITY();

        UPDATE dbo.PLAN_USER_REVIEW
        SET VISIBILITYSTATUS = N'UNDER_REVIEW',
            UPDATEDDATE      = SYSUTCDATETIME()
        WHERE REVIEWID = @REVIEWID
          AND VISIBILITYSTATUS = N'VISIBLE';

        SELECT 1 AS SUCCESS, @RID AS REPORTID, N'Flag submitted' AS MESSAGE;
    END TRY
    BEGIN CATCH
        SELECT 0 AS SUCCESS, CAST(NULL AS BIGINT) AS REPORTID, ERROR_MESSAGE() AS MESSAGE;
    END CATCH
END
GO


